/* ── NPC 帧集组装 ── */

export interface NpcArt {
  idle: PixelFrame[]
  walk: PixelFrame[]
  react: PixelFrame[]
  width: number
  height: number
}

interface NpcParts {
  palette: Record<string, string>
  body: string[]
  legsStand: string[]
  legsContactR: string[]
  legsContactL: string[]
  legsPassing: string[]
  bodyReact: string[]
  /** 反应帧用不同的腿带（如老人举杖后杖不在腿带里） */
  legsReact?: string[]
}

const buildNpc = (parts: NpcParts): NpcArt => {
  const frame = (bodyRows: string[]): PixelFrame => ({ rows: bodyRows, palette: parts.palette })
  const stand = compose(parts.body, parts.legsStand)
  const reactLegs = parts.legsReact ?? parts.legsStand
  const reactBase = compose(parts.bodyReact, reactLegs)
  const idle = [
    frame(stand),
    frame(shiftUp(stand)),
    frame(withBlink(stand)),
    frame(shiftUp(stand)),
  ]
  const walk = [
    frame(compose(parts.body, parts.legsContactR)),
    frame(compose(parts.body, parts.legsPassing)),
    frame(compose(parts.body, parts.legsContactL)),
    frame(compose(parts.body, parts.legsPassing)),
  ]
  const react = [frame(reactBase), frame(shiftUp(reactBase))]
  // 尺寸契约实测（杜绝手写 width/height 与点阵漂移）
  const size = validateFrame(idle[0]!)
  for (const f of [...idle, ...walk, ...react]) validateFrame(f)
  return { idle, walk, react, width: size.width, height: size.height }
}

