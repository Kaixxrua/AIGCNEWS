/**
 * 行内 $…$ 的认法，公式渲染（useLatexRenderer）和论文摘要排版（features/papers/paperLatex）共用一份，
 * 摘要排版认作公式、原样留下的，渲染时也正好当公式。
 *
 * 按 Pandoc 的规则认：开头的 $ 后、结尾的 $ 前都不能是空白，结尾的 $ 后不能紧跟数字。
 * 这样「$4/$20」「Pro $20/月，Max $200/月」之类的美元价格不会被当成公式
 * （2026-10-01 X 动态简报的定价段整段被渲染成公式）。
 */
export const INLINE_DOLLAR_MATH = String.raw`(?<!\$)\$(?![\s$])([^\n$]+?)(?<!\s)\$(?![\d$])`
