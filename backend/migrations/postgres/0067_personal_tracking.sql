CREATE TABLE tracking_settings (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    delivery_hour SMALLINT NOT NULL DEFAULT 8 CHECK (delivery_hour BETWEEN 0 AND 23),
    channel_id BIGINT REFERENCES push_channels(id) ON DELETE SET NULL,
    last_checked_at TIMESTAMPTZ
);
CREATE TABLE tracking_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('keyword', 'project')),
    query VARCHAR(120) NOT NULL CHECK (length(trim(query)) > 0),
    source TEXT NOT NULL DEFAULT 'all' CHECK (source IN ('all', 'github', 'arxiv', 'news', 'producthunt', 'hackernews', 'x', 'dailyhot')),
    excludes JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(excludes) = 'array'),
    star_threshold INTEGER NOT NULL DEFAULT 50 CHECK (star_threshold BETWEEN 1 AND 100000),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_tracking_rules_user ON tracking_rules (user_id, id);
CREATE TABLE tracking_digests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    issue_date DATE NOT NULL,
    items JSONB NOT NULL CHECK (jsonb_typeof(items) = 'array'),
    truncated BOOLEAN NOT NULL DEFAULT FALSE,
    channel_id BIGINT REFERENCES push_channels(id) ON DELETE SET NULL,
    delivery_status TEXT NOT NULL DEFAULT 'none' CHECK (delivery_status IN ('none', 'pending', 'sending', 'sent', 'failed', 'cancelled')),
    attempts SMALLINT NOT NULL DEFAULT 0,
    claimed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, issue_date)
);
CREATE INDEX idx_tracking_digest_pending ON tracking_digests (created_at)
    WHERE delivery_status IN ('pending', 'sending');
CREATE TABLE tracking_seen (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_key TEXT NOT NULL,
    seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, item_key)
);
