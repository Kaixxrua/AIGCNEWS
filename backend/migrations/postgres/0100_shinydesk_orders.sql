-- 闪光工坊（ShinyDesk）激活码订单：游客 PayPal 下单，与会员 payment_orders 分表。
-- 状态：pending（已建单待付）→ paid（PayPal capture COMPLETED 且金额币种核对通过）
--       → fulfilled（授权服务器已发码）→ revoked（退款/冲正/人工作废）；closed 为人工关单吸态。
-- 恰好一次：mark_paid / mark_fulfilled 都是带状态前提的条件 UPDATE；
-- 授权服务器以 paypal_order_id 为幂等键，重复发码请求返回同一个码。
CREATE TABLE shinydesk_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no TEXT NOT NULL UNIQUE CHECK (order_no ~ '^SD[0-9]{14}[A-F0-9]{8}$'),
    product_code TEXT NOT NULL,
    amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
    currency CHAR(3) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'fulfilled', 'revoked', 'closed')),
    access_token_hash CHAR(64) NOT NULL,
    paypal_order_id TEXT UNIQUE,
    paypal_capture_id TEXT UNIQUE,
    payer_email TEXT NOT NULL DEFAULT '',
    license_code TEXT NOT NULL DEFAULT '',
    license_id TEXT NOT NULL DEFAULT '',
    email_status TEXT NOT NULL DEFAULT 'none'
        CHECK (email_status IN ('none', 'sending', 'sent', 'failed', 'skipped')),
    email_attempts SMALLINT NOT NULL DEFAULT 0,
    dispute_status TEXT NOT NULL DEFAULT '',
    revoke_reason TEXT NOT NULL DEFAULT '',
    lookup_failures SMALLINT NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '',
    client_ip TEXT NOT NULL DEFAULT '',
    callback_payload TEXT NOT NULL DEFAULT '',
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    fulfilled_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_shinydesk_orders_payer_email ON shinydesk_orders (lower(payer_email));
CREATE INDEX idx_shinydesk_orders_status_created ON shinydesk_orders (status, created_at DESC);
