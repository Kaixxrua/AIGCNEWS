CREATE TABLE x_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(128) NOT NULL DEFAULT '',
    note TEXT,
    auth_token TEXT NOT NULL,
    ct0 TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    last_test_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    last_test_message TEXT,
    last_test_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE x_credentials_bootstrap_state (
    singleton_key INTEGER PRIMARY KEY DEFAULT 1 CHECK (singleton_key = 1),
    seeded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_x_credentials_enabled
    ON x_credentials (enabled, sort_order, id);
CREATE INDEX idx_x_credentials_status
    ON x_credentials (last_test_status, last_test_at);
