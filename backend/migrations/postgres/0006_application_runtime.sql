CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone VARCHAR(20) UNIQUE,
    email VARCHAR(255) UNIQUE,
    email_verified BOOLEAN NOT NULL DEFAULT TRUE,
    invite_code_used VARCHAR(64),
    username VARCHAR(64),
    hashed_password VARCHAR(256) NOT NULL,
    role TEXT DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE documents (
    id VARCHAR(255) PRIMARY KEY,
    source VARCHAR(64),
    source_channel VARCHAR(64) DEFAULT '',
    title VARCHAR(1024),
    url VARCHAR(1024),
    summary TEXT,
    published_date VARCHAR(64),
    tags TEXT,
    score DOUBLE PRECISION DEFAULT 0,
    raw_score DOUBLE PRECISION DEFAULT 0,
    rank_in_period INTEGER DEFAULT 9999,
    indexed BOOLEAN DEFAULT FALSE,
    created_at VARCHAR(64),
    in_daily BOOLEAN DEFAULT FALSE,
    in_weekly BOOLEAN DEFAULT FALSE,
    in_monthly BOOLEAN DEFAULT FALSE,
    local_pdf_path VARCHAR(512),
    stars INTEGER DEFAULT 0,
    forks INTEGER DEFAULT 0,
    language VARCHAR(128) DEFAULT ''
);

CREATE TABLE ingestion_tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'pending',
    started_at VARCHAR(64),
    finished_at VARCHAR(64),
    error_msg TEXT,
    item_count INTEGER DEFAULT 0
);

CREATE INDEX idx_ingestion_tasks_status_id
    ON ingestion_tasks (status, id DESC);

CREATE TABLE briefings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date VARCHAR(64) NOT NULL,
    content TEXT NOT NULL,
    created_at VARCHAR(64)
);

CREATE TABLE rag_evaluations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query TEXT NOT NULL,
    answer TEXT,
    sources_json TEXT,
    recall_score DOUBLE PRECISION,
    citation_score DOUBLE PRECISION,
    subjective_score DOUBLE PRECISION,
    evaluated_at VARCHAR(64)
);

CREATE TABLE document_rank_snapshots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id VARCHAR(255) NOT NULL,
    snapshot_date VARCHAR(16) NOT NULL,
    source_channel VARCHAR(64) NOT NULL,
    rank_in_period INTEGER,
    raw_score DOUBLE PRECISION,
    score DOUBLE PRECISION,
    created_at VARCHAR(64),
    CONSTRAINT uq_rank_snap
        UNIQUE (doc_id, snapshot_date, source_channel)
);

CREATE INDEX idx_snapshots_date_channel
    ON document_rank_snapshots (snapshot_date, source_channel);

CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    scope TEXT NOT NULL DEFAULT 'global'
        CHECK (scope IN ('global', 'paper')),
    scope_key VARCHAR(255),
    title VARCHAR(255),
    last_message_preview VARCHAR(500),
    message_count INTEGER NOT NULL DEFAULT 0,
    last_accessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_conv_user_updated
    ON conversations (user_id, updated_at DESC);
CREATE INDEX idx_conv_user_accessed
    ON conversations (user_id, last_accessed_at DESC);
CREATE INDEX idx_conv_scope
    ON conversations (user_id, scope, scope_key);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL
        REFERENCES conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    thinking TEXT,
    sources_json JSONB,
    attachments_json JSONB,
    status TEXT NOT NULL DEFAULT 'done'
        CHECK (status IN ('done', 'streaming', 'deleted', 'regenerated')),
    parent_message_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_msg_conversation_created
    ON chat_messages (conversation_id, created_at, id);
CREATE INDEX idx_msg_parent ON chat_messages (parent_message_id);

CREATE TABLE chat_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    conversation_id BIGINT REFERENCES conversations(id) ON DELETE SET NULL,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    modality TEXT NOT NULL CHECK (modality IN ('image', 'pdf')),
    storage_path VARCHAR(512),
    file_size BIGINT NOT NULL DEFAULT 0,
    page_count INTEGER,
    parse_status TEXT NOT NULL DEFAULT 'uploaded'
        CHECK (parse_status IN ('uploaded', 'processing', 'ready', 'failed')),
    extract_text TEXT,
    meta_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_attachment_user_created
    ON chat_attachments (user_id, created_at DESC);
CREATE INDEX idx_attachment_conv ON chat_attachments (conversation_id);

CREATE TABLE runtime_provider_settings (
    provider VARCHAR(64) PRIMARY KEY,
    base_url VARCHAR(1024) DEFAULT '',
    api_key TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    model_name VARCHAR(255) DEFAULT ''
);

CREATE TABLE mcp_server_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_key VARCHAR(64) NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    description TEXT,
    url VARCHAR(1024) NOT NULL,
    transport VARCHAR(32) NOT NULL DEFAULT 'streamable_http',
    auth_type VARCHAR(32) NOT NULL DEFAULT 'none',
    auth_token TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_test_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    last_test_message TEXT,
    last_test_at TIMESTAMPTZ,
    last_tools_json TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_mcp_server_configs_key UNIQUE (server_key)
);

CREATE INDEX idx_mcp_server_configs_enabled
    ON mcp_server_configs (enabled, updated_at);
CREATE INDEX idx_mcp_server_configs_status
    ON mcp_server_configs (last_test_status, last_test_at);

CREATE TABLE user_mcp_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    token_hint VARCHAR(32) NOT NULL,
    scopes_json TEXT NOT NULL,
    client_type VARCHAR(32) NOT NULL,
    client_label VARCHAR(128) NOT NULL DEFAULT '',
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ,
    CONSTRAINT uq_user_mcp_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX idx_user_mcp_tokens_user_created
    ON user_mcp_tokens (user_id, created_at DESC);
CREATE INDEX idx_user_mcp_tokens_active
    ON user_mcp_tokens (user_id, revoked_at, deleted_at, expires_at);

CREATE TABLE briefing_subscriptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email VARCHAR(255) NOT NULL,
    source VARCHAR(32) NOT NULL DEFAULT 'all',
    period VARCHAR(16) NOT NULL DEFAULT 'daily',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sub_user_source_period UNIQUE (user_id, source, period)
);

CREATE INDEX idx_sub_active
    ON briefing_subscriptions (is_active, source, period);
