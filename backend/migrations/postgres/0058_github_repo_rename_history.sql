-- Preserve searchable GitHub repository rename history without retaining old
-- candidate/enrichment/semantic business rows.
CREATE TABLE IF NOT EXISTS github_repo_rename_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_repo_id VARCHAR(255) NOT NULL
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    old_full_name VARCHAR(255) NOT NULL,
    new_full_name VARCHAR(255) NOT NULL,
    observed_at TEXT NOT NULL,
    source VARCHAR(64) NOT NULL DEFAULT '',
    UNIQUE (canonical_repo_id, old_full_name, new_full_name)
);

CREATE INDEX IF NOT EXISTS idx_gh_rename_history_old_name
    ON github_repo_rename_history (LOWER(old_full_name));
CREATE INDEX IF NOT EXISTS idx_gh_rename_history_canonical
    ON github_repo_rename_history (canonical_repo_id, observed_at DESC);
