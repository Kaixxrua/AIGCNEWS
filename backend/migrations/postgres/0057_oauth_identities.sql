-- OAuth identities are keyed by the provider subject, never by email alone.
-- The users column is additive and defaults TRUE for all legacy password users.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS password_login_enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS user_oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider TEXT NOT NULL CHECK (provider IN ('github', 'google', 'wechat')),
    provider_subject TEXT NOT NULL
        CHECK (length(btrim(provider_subject)) > 0),
    display_email VARCHAR(255),
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
        CHECK (NOT email_verified OR display_email IS NOT NULL),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_oauth_identity_provider_subject
        UNIQUE (provider, provider_subject)
);

CREATE INDEX IF NOT EXISTS idx_user_oauth_identities_user_id
    ON user_oauth_identities (user_id);
