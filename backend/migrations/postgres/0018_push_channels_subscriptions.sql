CREATE TABLE push_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel_type VARCHAR(16) NOT NULL,
    target VARCHAR(512) NOT NULL,
    encrypted_config TEXT,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_push_channels_type CHECK (channel_type IN ('email')),
    CONSTRAINT ck_push_channels_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT uq_push_channels_user_type_target UNIQUE (user_id, channel_type, target)
);

CREATE INDEX idx_push_channels_user
    ON push_channels (user_id);

CREATE TABLE user_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel_id BIGINT NOT NULL REFERENCES push_channels(id) ON DELETE CASCADE,
    source VARCHAR(32) NOT NULL DEFAULT 'all',
    frequency VARCHAR(16) NOT NULL DEFAULT 'daily',
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_subscriptions_frequency CHECK (frequency IN ('daily', 'weekly', 'monthly')),
    CONSTRAINT ck_user_subscriptions_status CHECK (status IN ('active', 'paused')),
    CONSTRAINT uq_user_subscriptions_user_channel_source
        UNIQUE (user_id, channel_id, source, frequency)
);

CREATE INDEX idx_user_subscriptions_user
    ON user_subscriptions (user_id);

CREATE INDEX idx_user_subscriptions_dispatch
    ON user_subscriptions (status, frequency, source);
