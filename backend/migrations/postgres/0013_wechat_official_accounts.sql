CREATE TABLE wechat_login_attempts (
    attempt_id UUID PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    encrypted_uuid_cookie TEXT NOT NULL,
    encrypted_uuid_cookie_nonce TEXT NOT NULL,
    encryption_key_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'waiting_scan',
    upstream_status INTEGER,
    expires_at TIMESTAMPTZ NOT NULL,
    error_code VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_wechat_login_attempt_status CHECK (
        status IN (
            'waiting_scan',
            'scanned_waiting_confirmation',
            'confirmed',
            'completed',
            'qr_expired',
            'failed',
            'cancelled'
        )
    )
);

CREATE INDEX idx_wechat_login_attempts_owner_status
    ON wechat_login_attempts (owner_id, status, expires_at);
CREATE INDEX idx_wechat_login_attempts_expiry
    ON wechat_login_attempts (expires_at);

CREATE TABLE wechat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    encrypted_token TEXT NOT NULL,
    encrypted_token_nonce TEXT NOT NULL,
    encrypted_cookie TEXT NOT NULL,
    encrypted_cookie_nonce TEXT NOT NULL,
    encryption_key_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    account_name VARCHAR(255) NOT NULL DEFAULT '',
    account_avatar_url TEXT NOT NULL DEFAULT '',
    last_validated_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    invalid_reason_code VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wechat_sessions_owner UNIQUE (owner_id),
    CONSTRAINT ck_wechat_session_status CHECK (status IN ('active', 'invalid'))
);

CREATE INDEX idx_wechat_sessions_status_expiry
    ON wechat_sessions (status, expires_at);

CREATE TABLE wechat_official_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    fakeid VARCHAR(255) NOT NULL,
    nickname VARCHAR(255) NOT NULL DEFAULT '',
    alias VARCHAR(255) NOT NULL DEFAULT '',
    avatar_url TEXT NOT NULL DEFAULT '',
    signature TEXT NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    last_sync_status VARCHAR(32) NOT NULL DEFAULT 'never',
    last_sync_message TEXT NOT NULL DEFAULT '',
    last_sync_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wechat_official_accounts_owner_fakeid UNIQUE (owner_id, fakeid),
    CONSTRAINT ck_wechat_account_sync_status CHECK (
        last_sync_status IN ('never', 'queued', 'running', 'succeeded', 'failed')
    )
);

CREATE INDEX idx_wechat_official_accounts_owner_enabled
    ON wechat_official_accounts (owner_id, enabled, sort_order, id);

CREATE TABLE wechat_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES wechat_official_accounts(id) ON DELETE CASCADE,
    stable_article_key VARCHAR(512) NOT NULL,
    message_id VARCHAR(255) NOT NULL DEFAULT '',
    itemidx INTEGER NOT NULL DEFAULT 1,
    title TEXT NOT NULL DEFAULT '',
    digest TEXT NOT NULL DEFAULT '',
    author VARCHAR(255) NOT NULL DEFAULT '',
    article_url TEXT NOT NULL DEFAULT '',
    cover_url TEXT NOT NULL DEFAULT '',
    source_url TEXT NOT NULL DEFAULT '',
    published_at TIMESTAMPTZ,
    raw_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wechat_articles_account_stable_key UNIQUE (
        account_id,
        stable_article_key
    ),
    CONSTRAINT ck_wechat_articles_itemidx CHECK (itemidx >= 1)
);

CREATE INDEX idx_wechat_articles_account_published
    ON wechat_articles (account_id, published_at DESC, id DESC);
