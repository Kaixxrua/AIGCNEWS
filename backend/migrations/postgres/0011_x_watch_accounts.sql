CREATE TABLE x_watch_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_name VARCHAR(64) NOT NULL,
    display_name VARCHAR(128) NOT NULL DEFAULT '',
    note TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    last_test_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    last_test_message TEXT,
    last_test_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_x_watch_accounts_screen_name UNIQUE (screen_name)
);

CREATE INDEX idx_x_watch_accounts_enabled
    ON x_watch_accounts (enabled, sort_order, id);
