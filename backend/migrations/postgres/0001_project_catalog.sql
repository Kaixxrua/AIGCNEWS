CREATE TABLE github_repo_candidates (
    repo_id VARCHAR(255) PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(512),
    url TEXT,
    description TEXT,
    language VARCHAR(128),
    topics_json TEXT,
    created_at TEXT,
    pushed_at TEXT,
    stars BIGINT NOT NULL DEFAULT 0,
    forks BIGINT NOT NULL DEFAULT 0,
    watchers BIGINT NOT NULL DEFAULT 0,
    source_channels TEXT NOT NULL DEFAULT '',
    first_seen_at TEXT,
    last_seen_at TEXT,
    last_snapshot_at TEXT
);

CREATE UNIQUE INDEX uq_gh_candidates_full_name_ci
    ON github_repo_candidates (LOWER(full_name));
CREATE INDEX idx_gh_candidates_stars
    ON github_repo_candidates (stars DESC, forks DESC, full_name);
CREATE INDEX idx_gh_candidates_pushed
    ON github_repo_candidates (pushed_at DESC, stars DESC);
CREATE INDEX idx_gh_candidates_first_seen
    ON github_repo_candidates (first_seen_at DESC, stars DESC);
CREATE INDEX idx_gh_candidates_language
    ON github_repo_candidates (LOWER(language), stars DESC);

CREATE TABLE github_repo_aliases (
    alias_repo_id VARCHAR(255) PRIMARY KEY,
    canonical_repo_id VARCHAR(255) NOT NULL
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    full_name VARCHAR(255) NOT NULL,
    created_at TEXT,
    updated_at TEXT
);

CREATE INDEX idx_gh_repo_alias_canonical ON github_repo_aliases (canonical_repo_id);
CREATE INDEX idx_gh_repo_alias_full_name ON github_repo_aliases (LOWER(full_name));

CREATE TABLE github_repo_enrichments (
    repo_id VARCHAR(255) PRIMARY KEY
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    category_slug VARCHAR(64) NOT NULL,
    category_name VARCHAR(128) NOT NULL,
    subcategory_slug VARCHAR(64) NOT NULL DEFAULT '',
    subcategory_name VARCHAR(128) NOT NULL DEFAULT '',
    description_zh VARCHAR(512) NOT NULL,
    tags_json TEXT,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    source_fingerprint CHAR(64) NOT NULL,
    prompt_version VARCHAR(32) NOT NULL,
    model_provider VARCHAR(64) NOT NULL DEFAULT '',
    model_name VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'succeeded',
    error_msg TEXT,
    enriched_at TEXT,
    updated_at TEXT
);

CREATE INDEX idx_gh_repo_enrich_category
    ON github_repo_enrichments (category_slug, status);
CREATE INDEX idx_gh_repo_enrich_subcategory
    ON github_repo_enrichments (subcategory_slug, status);
CREATE INDEX idx_gh_repo_enrich_category_subcategory
    ON github_repo_enrichments (category_slug, subcategory_slug, status);
CREATE INDEX idx_gh_repo_enrich_status
    ON github_repo_enrichments (status, updated_at DESC);

CREATE TABLE github_repo_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id VARCHAR(255) NOT NULL
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    snapshot_date VARCHAR(16) NOT NULL,
    captured_at TEXT NOT NULL,
    stars BIGINT NOT NULL DEFAULT 0,
    forks BIGINT NOT NULL DEFAULT 0,
    watchers BIGINT NOT NULL DEFAULT 0,
    community_metrics_complete BOOLEAN,
    open_issues BIGINT NOT NULL DEFAULT 0,
    repo_created_at TEXT,
    repo_pushed_at TEXT,
    UNIQUE (repo_id, snapshot_date)
);

CREATE INDEX idx_gh_snapshots_date_repo
    ON github_repo_snapshots (snapshot_date DESC, repo_id);

CREATE TABLE github_repo_daily_metrics (
    repo_id VARCHAR(255) NOT NULL
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    metric_date VARCHAR(16) NOT NULL,
    stars BIGINT NOT NULL DEFAULT 0,
    forks BIGINT NOT NULL DEFAULT 0,
    watchers BIGINT NOT NULL DEFAULT 0,
    open_issues BIGINT NOT NULL DEFAULT 0,
    previous_snapshot_date VARCHAR(16),
    previous_stars BIGINT NOT NULL DEFAULT 0,
    daily_star_growth BIGINT NOT NULL DEFAULT 0,
    daily_fork_growth BIGINT NOT NULL DEFAULT 0,
    daily_watcher_growth BIGINT NOT NULL DEFAULT 0,
    daily_growth_available BOOLEAN NOT NULL DEFAULT FALSE,
    daily_growth_source VARCHAR(32) NOT NULL DEFAULT 'unavailable',
    daily_growth_observed_at TEXT,
    scale_corrected_growth_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    growth_acceleration_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    absolute_growth_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    maintenance_activity_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    community_engagement_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    hot_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    score_version VARCHAR(32) NOT NULL DEFAULT 'daily_hot_v4',
    updated_at TEXT,
    PRIMARY KEY (repo_id, metric_date)
);

CREATE INDEX idx_gh_daily_metrics_date_hot
    ON github_repo_daily_metrics (metric_date DESC, hot_score DESC);
CREATE INDEX idx_gh_daily_metrics_date_growth
    ON github_repo_daily_metrics (metric_date DESC, daily_star_growth DESC);

CREATE TABLE github_trending_hits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id VARCHAR(255) NOT NULL
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    full_name VARCHAR(255) NOT NULL,
    period VARCHAR(16) NOT NULL,
    language VARCHAR(128),
    rank INTEGER,
    observed_date VARCHAR(16) NOT NULL,
    captured_at TEXT NOT NULL,
    period_star_growth BIGINT,
    period_growth_observed_at TEXT,
    UNIQUE (repo_id, period, observed_date)
);

CREATE INDEX idx_gh_trending_period_date
    ON github_trending_hits (period, observed_date DESC, rank);

CREATE TABLE github_repo_recommendations (
    repo_id VARCHAR(255) PRIMARY KEY
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    recommended_by_user_id BIGINT,
    recommended_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_gh_repo_recommendations_active
    ON github_repo_recommendations (active, recommended_at DESC);
CREATE INDEX idx_gh_repo_recommendations_user
    ON github_repo_recommendations (recommended_by_user_id);

CREATE TABLE github_project_semantic_sources (
    repo_id VARCHAR(255) PRIMARY KEY
        REFERENCES github_repo_candidates(repo_id) ON DELETE CASCADE,
    readme_text TEXT,
    readme_sha256 CHAR(64) NOT NULL DEFAULT '',
    readme_etag TEXT NOT NULL DEFAULT '',
    readme_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    readme_checked_at TEXT,
    readme_fetched_at TEXT,
    readme_repo_pushed_at TEXT,
    readme_error TEXT,
    readme_retry_count INTEGER NOT NULL DEFAULT 0,
    readme_next_retry_at TEXT,
    source_fingerprint CHAR(64) NOT NULL DEFAULT '',
    indexed_fingerprint CHAR(64) NOT NULL DEFAULT '',
    index_version VARCHAR(32) NOT NULL DEFAULT '',
    embedding_provider VARCHAR(64) NOT NULL DEFAULT '',
    embedding_model VARCHAR(255) NOT NULL DEFAULT '',
    embedding_dimension INTEGER NOT NULL DEFAULT 0,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    index_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    index_error TEXT,
    index_retry_count INTEGER NOT NULL DEFAULT 0,
    index_next_retry_at TEXT,
    indexed_at TEXT,
    updated_at TEXT
);

CREATE INDEX idx_project_semantic_readme_status
    ON github_project_semantic_sources (readme_status, readme_checked_at);
CREATE INDEX idx_project_semantic_index_status
    ON github_project_semantic_sources (index_status, indexed_at);
CREATE INDEX idx_project_semantic_fingerprint
    ON github_project_semantic_sources (indexed_fingerprint);

CREATE TABLE tool_websites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_url TEXT NOT NULL,
    normalized_url_hash CHAR(64) NOT NULL UNIQUE,
    domain VARCHAR(255) NOT NULL,
    title VARCHAR(512) NOT NULL DEFAULT '',
    description TEXT,
    image_url TEXT NOT NULL DEFAULT '',
    raw_metadata_json TEXT,
    fetch_status VARCHAR(32) NOT NULL DEFAULT 'succeeded',
    fetch_error TEXT,
    source_fingerprint CHAR(64) NOT NULL,
    visibility VARCHAR(16) NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'private')),
    added_by_user_id BIGINT,
    first_seen_at TEXT,
    last_seen_at TEXT,
    updated_at TEXT
);

CREATE INDEX idx_tool_website_domain ON tool_websites (domain);
CREATE INDEX idx_tool_website_visibility
    ON tool_websites (visibility, first_seen_at DESC);
CREATE INDEX idx_tool_website_added_by_user ON tool_websites (added_by_user_id);
CREATE INDEX idx_tool_website_fetch_status
    ON tool_websites (fetch_status, updated_at DESC);

CREATE TABLE tool_website_enrichments (
    website_id BIGINT PRIMARY KEY REFERENCES tool_websites(id) ON DELETE CASCADE,
    category_slug VARCHAR(64) NOT NULL,
    category_name VARCHAR(128) NOT NULL,
    subcategory_slug VARCHAR(64) NOT NULL DEFAULT '',
    subcategory_name VARCHAR(128) NOT NULL DEFAULT '',
    description_zh VARCHAR(512) NOT NULL,
    tags_json TEXT,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    source_fingerprint CHAR(64) NOT NULL,
    prompt_version VARCHAR(32) NOT NULL,
    model_provider VARCHAR(64) NOT NULL DEFAULT '',
    model_name VARCHAR(255) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'succeeded',
    error_msg TEXT,
    enriched_at TEXT,
    updated_at TEXT
);

CREATE INDEX idx_tool_website_enrich_category
    ON tool_website_enrichments (category_slug, status);
CREATE INDEX idx_tool_website_enrich_subcategory
    ON tool_website_enrichments (subcategory_slug, status);
CREATE INDEX idx_tool_website_enrich_category_subcategory
    ON tool_website_enrichments (category_slug, subcategory_slug, status);
CREATE INDEX idx_tool_website_enrich_status
    ON tool_website_enrichments (status, updated_at DESC);

CREATE TABLE project_favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    project_source VARCHAR(16) NOT NULL
        CHECK (project_source IN ('github', 'website')),
    project_id VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, project_source, project_id)
);

CREATE INDEX idx_project_favorites_user_created
    ON project_favorites (user_id, created_at DESC);
CREATE INDEX idx_project_favorites_item
    ON project_favorites (project_source, project_id);

CREATE TABLE user_tool_websites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    website_id BIGINT NOT NULL REFERENCES tool_websites(id) ON DELETE CASCADE,
    added_via VARCHAR(16) NOT NULL DEFAULT 'auto'
        CHECK (added_via IN ('auto', 'manual', 'existing')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, website_id)
);

CREATE INDEX idx_user_tool_websites_user_created
    ON user_tool_websites (user_id, created_at DESC);
CREATE INDEX idx_user_tool_websites_website ON user_tool_websites (website_id);

CREATE TABLE user_tool_website_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    website_id BIGINT NOT NULL REFERENCES tool_websites(id) ON DELETE CASCADE,
    title VARCHAR(512) NOT NULL DEFAULT '',
    description TEXT,
    image_url TEXT NOT NULL DEFAULT '',
    description_zh VARCHAR(512) NOT NULL DEFAULT '',
    category_slug VARCHAR(64) NOT NULL DEFAULT '',
    category_name VARCHAR(128) NOT NULL DEFAULT '',
    subcategory_slug VARCHAR(64) NOT NULL DEFAULT '',
    subcategory_name VARCHAR(128) NOT NULL DEFAULT '',
    tags_json TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, website_id)
);

CREATE INDEX idx_user_tool_website_override_user
    ON user_tool_website_overrides (user_id, updated_at DESC);
CREATE INDEX idx_user_tool_website_override_website
    ON user_tool_website_overrides (website_id);
