-- 会员 RSS feed 专用 token：与 MCP access token 彻底分离的独立凭证域。
--
-- 设计要点：
--   - 每用户至多一个活跃 token（partial unique index 强制），所有 feed 渠道
--     共用；用户「重新生成」即吊销旧 token（rotation 自愈 URL 泄漏）。
--   - 无 expires_at：token 永不过期，访问控制完全靠请求时校验
--     （revoked_at IS NULL + users.disabled = FALSE + 生效会员档位判定）。
--   - token_hash 存 SHA-256；token_encrypted 存 AES-256-GCM 密封的明文，
--     供用户回显完整 RSS 链接（密钥独立：feed_token_encryption_key）。
CREATE TABLE IF NOT EXISTS user_feed_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL,
    token_hint VARCHAR(32) NOT NULL,
    token_encrypted TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_user_feed_tokens_hash UNIQUE (token_hash)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_feed_tokens_active_user
    ON user_feed_tokens (user_id)
    WHERE revoked_at IS NULL;
